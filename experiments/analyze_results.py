#!/usr/bin/env python3
"""
Turn run_grid.py output into paper-ready tables (LaTeX + markdown) and figures.

Expects results/<dataset>_all.csv produced by run_grid.py.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

DATASETS = ["elliptic", "yelp", "amazon"]
NORM_ORDER = ["none", "batch", "layer", "graph", "pair"]
INIT_ORDER = ["default", "xavier", "kaiming"]
MODEL_ORDER = ["GCN", "GAT", "SAGE"]


def agg_table(df: pd.DataFrame, metric="auprc") -> pd.DataFrame:
    """mean +/- std over seeds for every (model, init, norm)."""
    g = df.groupby(["model", "init", "norm"])[metric].agg(["mean", "std", "count"])
    return g.reset_index()


def latex_main_table(df: pd.DataFrame, dataset: str, metric="auprc") -> str:
    """One block per model: rows = init, cols = norm, cell = mean+-std."""
    lines = [
        "% Auto-generated by analyze_results.py — " + dataset,
        "\\begin{table}[t]\\centering",
        f"\\caption{{{metric.upper()} (mean $\\pm$ std over 5 seeds) on {dataset}. "
        "Best per architecture in bold.}",
        f"\\label{{tab:grid_{dataset}_{metric}}}",
        "\\begin{tabular}{llccccc}",
        "\\toprule",
        "Model & Init & None & BatchNorm & LayerNorm & GraphNorm & PairNorm \\\\",
        "\\midrule",
    ]
    a = agg_table(df, metric)
    for m in MODEL_ORDER:
        sub = a[a.model == m]
        if sub.empty:
            continue
        best = sub["mean"].max()
        for j, ini in enumerate(INIT_ORDER):
            cells = []
            for nrm in NORM_ORDER:
                r = sub[(sub.init == ini) & (sub.norm == nrm)]
                if r.empty:
                    cells.append("--")
                else:
                    mu, sd = r["mean"].iloc[0], r["std"].iloc[0]
                    cell = f"{mu:.4f}$\\pm${sd:.3f}"
                    if abs(mu - best) < 1e-9:
                        cell = f"\\textbf{{{cell}}}"
                    cells.append(cell)
            head = m if j == 0 else ""
            lines.append(f"{head} & {ini} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if m != MODEL_ORDER[-1] else "\\bottomrule")
    lines += ["\\end{tabular}", "\\end{table}"]
    return "\n".join(lines)


def significance(df: pd.DataFrame, dataset: str, metric="auprc") -> pd.DataFrame:
    """Paired t-test + Wilcoxon of every config against the per-model baseline.
    Conference baseline (repo scripts/train.py preset 'baseline') = default init,
    NO norm layer."""
    rows = []
    for m in MODEL_ORDER:
        base = df[(df.model == m) & (df.init == "default") & (df.norm == "none")]
        base = base.sort_values("seed")[metric].values
        for ini in INIT_ORDER:
            for nrm in NORM_ORDER:
                sel = df[(df.model == m) & (df.init == ini) & (df.norm == nrm)]
                v = sel.sort_values("seed")[metric].values
                if len(v) == 0 or len(v) != len(base):
                    continue
                d = v - base
                if np.allclose(d, 0):
                    t_p = w_p = 1.0
                else:
                    t_p = stats.ttest_rel(v, base).pvalue
                    try:
                        w_p = stats.wilcoxon(v, base).pvalue
                    except ValueError:
                        w_p = 1.0
                rows.append(dict(dataset=dataset, model=m, init=ini, norm=nrm,
                                 mean=v.mean(), delta=d.mean(),
                                 t_pvalue=t_p, wilcoxon_pvalue=w_p,
                                 significant_05=bool(t_p < 0.05)))
    return pd.DataFrame(rows)


def best_configs(df: pd.DataFrame, metric="auprc") -> pd.DataFrame:
    a = agg_table(df, metric)
    return a.loc[a.groupby("model")["mean"].idxmax()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="analysis")
    args = ap.parse_args()
    rdir, odir = Path(args.results), Path(args.out)
    odir.mkdir(parents=True, exist_ok=True)

    all_sig = []
    for ds in DATASETS:
        f = rdir / f"{ds}_all.csv"
        if not f.exists():
            print(f"skip {ds} (no {f})")
            continue
        df = pd.read_csv(f)
        print(f"\n=== {ds}: {len(df)} runs ===")

        for metric in ["auprc", "auc"]:
            (odir / f"table_{ds}_{metric}.tex").write_text(latex_main_table(df, ds, metric))
        agg_table(df, "auprc").to_csv(odir / f"agg_{ds}_auprc.csv", index=False)
        agg_table(df, "mad").to_csv(odir / f"agg_{ds}_mad.csv", index=False)
        agg_table(df, "best_epoch").to_csv(odir / f"agg_{ds}_convergence.csv", index=False)

        sig = significance(df, ds)
        sig.to_csv(odir / f"significance_{ds}.csv", index=False)
        all_sig.append(sig)

        print("Best configs (AUPRC):")
        print(best_configs(df).to_string(index=False))

    if all_sig:
        pd.concat(all_sig).to_csv(odir / "significance_all.csv", index=False)
    print(f"\nDone -> {odir}/  (LaTeX tables: table_<dataset>_<metric>.tex)")


if __name__ == "__main__":
    main()
